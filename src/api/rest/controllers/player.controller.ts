import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  Post,
  Put,
  Query,
} from '@nestjs/common'
import { CommandBus, QueryBus } from '@nestjs/cqrs'
import {
  ApiBearerAuth,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger'
import { ZodResponse } from 'nestjs-zod'
import {
  DeletePlayerCommand,
  ListPlayersQuery,
  UpsertPlayerCommand,
} from '@/domain/player'
import { CurrentUserId } from '../../common/decorators'
import {
  ListPlayersQueryDto,
  PlayerCreateBodyDto,
  PlayerIdParamDto,
  PlayerResponseDto,
  PlayersResponseDto,
  PlayerUpsertBodyDto,
} from '../dto'
import { ApiErrorResponses } from '../errors'

@ApiTags('players')
@ApiBearerAuth()
@Controller({ path: 'players', version: '1' })
export class PlayerController {
  constructor(
    private readonly queryBus: QueryBus,
    private readonly commandBus: CommandBus,
  ) {}

  @Get()
  @ApiOperation({
    summary: "List the current user's players",
    description:
      'Live players only, or every change after `updatedSince` (tombstones included).',
  })
  @ZodResponse({ status: 200, type: PlayersResponseDto })
  @ApiErrorResponses(400, 401, 500)
  async list(
    @CurrentUserId() userId: string,
    @Query() query: ListPlayersQueryDto,
  ): Promise<PlayersResponseDto> {
    const players = await this.queryBus.execute(
      new ListPlayersQuery({
        userId,
        updatedSince: query.updatedSince ? new Date(query.updatedSince) : null,
      }),
    )
    return PlayersResponseDto.fromDomain(players)
  }

  @Post()
  @ApiOperation({
    summary: 'Create a player',
    description:
      'The id is generated by the client. Idempotent: replaying the same body changes nothing. An id used by another user is a 409.',
  })
  @ZodResponse({ status: 201, type: PlayerResponseDto })
  @ApiErrorResponses(400, 401, 409, 500)
  async create(
    @CurrentUserId() userId: string,
    @Body() body: PlayerCreateBodyDto,
  ): Promise<PlayerResponseDto> {
    return this.upsert(userId, body.id, body)
  }

  @Put(':id')
  @ApiOperation({
    summary: 'Create or replace a player',
    description:
      'Upsert: an unknown id creates the player. The most recent `updatedAt` wins.',
  })
  @ZodResponse({ status: 200, type: PlayerResponseDto })
  @ApiErrorResponses(400, 401, 409, 500)
  async replace(
    @CurrentUserId() userId: string,
    @Param() params: PlayerIdParamDto,
    @Body() body: PlayerUpsertBodyDto,
  ): Promise<PlayerResponseDto> {
    return this.upsert(userId, params.id, body)
  }

  @Delete(':id')
  @HttpCode(204)
  @ApiOperation({
    summary: 'Delete a player',
    description:
      'Idempotent soft delete (tombstone). Plays keep the name and style of the player.',
  })
  @ApiResponse({ status: 204, description: 'Player is deleted' })
  @ApiErrorResponses(400, 401, 500)
  async remove(
    @CurrentUserId() userId: string,
    @Param() params: PlayerIdParamDto,
  ): Promise<void> {
    await this.commandBus.execute(
      new DeletePlayerCommand({ userId, id: params.id }),
    )
  }

  private async upsert(
    userId: string,
    id: string,
    body: PlayerUpsertBodyDto,
  ): Promise<PlayerResponseDto> {
    const now = new Date()
    const { entity } = await this.commandBus.execute(
      new UpsertPlayerCommand({
        userId,
        id,
        name: body.name,
        color: body.color,
        shape: body.shape,
        handle: body.handle,
        isCurrentUser: body.isCurrentUser ?? false,
        createdAt: body.createdAt ? new Date(body.createdAt) : now,
        updatedAt: body.updatedAt ? new Date(body.updatedAt) : now,
      }),
    )
    return PlayerResponseDto.fromDomain(entity)
  }
}
