import { Controller, Get, Param, Query, Res } from '@nestjs/common'
import { CommandBus, QueryBus } from '@nestjs/cqrs'
import { ApiHeader, ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger'
import { Throttle } from '@nestjs/throttler'
import type { FastifyReply } from 'fastify'
import { ZodResponse, ZodSerializerDto } from 'nestjs-zod'
import {
  AGGREGATION_POLL_INTERVAL_SECONDS,
  FindGamesByBarcodeCommand,
  GetGameScoringTemplateQuery,
  RequestGameSheetCommand,
  SearchGamesQuery,
} from '@/domain/game'
import { ErrorCode } from '@/shared/errors'
import { type Locale, SUPPORTED_LOCALES } from '@/shared/i18n/locale'
import { ErrorCodeOnFailure, Language, Public } from '../../common/decorators'
import {
  GameBarcodeParamDto,
  GameIdParamDto,
  GameLookupResponseSchema,
  GamePendingResponseDto,
  GameResponseDto,
  GameSearchResponseDto,
  ScoringTemplateResponseDto,
  SearchGamesQueryDto,
} from '../dto'
import { ApiErrorResponses } from '../errors'

/** Each unknown barcode costs an external lookup, and the route is public. */
const BARCODE_THROTTLE = { default: { ttl: 60_000, limit: 10 } }

@ApiTags('games')
@Public()
@ApiHeader({
  name: 'accept-language',
  required: true,
  description: `Content language (${SUPPORTED_LOCALES.join(', ')}). Missing: 400 LANGUAGE_REQUIRED; no supported language: 400 UNSUPPORTED_LANGUAGE.`,
})
@Controller({ path: 'games', version: '1' })
export class GameController {
  constructor(
    private readonly queryBus: QueryBus,
    private readonly commandBus: CommandBus,
  ) {}

  @Get()
  @ApiOperation({
    summary: 'Search games by name (autocomplete)',
    description:
      'Games whose canonical name or Accept-Language name contains `search`, ignoring case and accents. Names starting with `search` are returned first.',
  })
  @ZodResponse({ status: 200, type: GameSearchResponseDto })
  @ApiErrorResponses(400, 500)
  async search(
    @Query() query: SearchGamesQueryDto,
    @Language() language: Locale,
  ): Promise<GameSearchResponseDto> {
    const results = await this.queryBus.execute(
      new SearchGamesQuery({
        search: query.search,
        limit: query.limit,
        language,
      }),
    )
    return GameSearchResponseDto.fromDomain(results)
  }

  // Declared before `:id` so that `barcodes` is not taken for a game id.
  @Get('barcodes/:code')
  @Throttle(BARCODE_THROTTLE)
  @ApiOperation({
    summary: 'Find games by barcode',
    description:
      'Games sold under an EAN / UPC barcode, named in the Accept-Language language when known. Known barcodes are answered from the database; unknown ones are looked up externally (slow), and the result is saved: barcodes matching a single game are linked to it, barcodes matching nothing are never looked up again. Usually one game; several when the barcode is a bundle; empty when nothing matches.',
  })
  @ZodResponse({ status: 200, type: GameSearchResponseDto })
  @ApiErrorResponses(400, 429, 500)
  @ErrorCodeOnFailure(ErrorCode.GAME_BARCODE_LOOKUP_FAILED)
  async findByBarcode(
    @Param() params: GameBarcodeParamDto,
    @Language() language: Locale,
  ): Promise<GameSearchResponseDto> {
    const results = await this.commandBus.execute(
      new FindGamesByBarcodeCommand({ code: params.code, language }),
    )
    return GameSearchResponseDto.fromDomain(results)
  }

  @Get(':id/scoring')
  @ApiOperation({
    summary: 'Get the score sheet template of a game',
    description:
      'Describes the score sheet to display for a play: its columns (`sides`), its lines (`rounds`, `rows`) and how the winner is designated (`outcome`). Texts are in the Accept-Language language. A game without a template gets the default one: a single score per player, highest wins.',
  })
  @ZodResponse({ status: 200, type: ScoringTemplateResponseDto })
  @ApiErrorResponses(400, 404, 500)
  async findScoringTemplate(
    @Param() params: GameIdParamDto,
    @Language() language: Locale,
  ): Promise<ScoringTemplateResponseDto> {
    const template = await this.queryBus.execute(
      new GetGameScoringTemplateQuery({ gameId: params.id, language }),
    )
    return ScoringTemplateResponseDto.fromDomain(template)
  }

  @Get(':id')
  @ApiOperation({
    summary: 'Get a game and its rule sheet',
    description:
      'The sheet is written in the Accept-Language language. On the first request in a language, it is generated by AI (or translated if it already exists in another language) in the background: the route answers 202 until it is ready, and the client calls it again after `retryAfterSeconds` (Retry-After header). If the aggregation fails, subsequent calls answer 500 for a few minutes, then a new attempt is started.',
  })
  @ZodSerializerDto(GameLookupResponseSchema)
  @ApiResponse({ status: 200, type: GameResponseDto })
  @ApiResponse({ status: 202, type: GamePendingResponseDto.Output })
  @ApiErrorResponses(400, 404, 500)
  @ErrorCodeOnFailure(ErrorCode.GAME_SHEET_GENERATION_FAILED)
  async findOne(
    @Param() params: GameIdParamDto,
    @Language() language: Locale,
    @Res({ passthrough: true }) reply: FastifyReply,
  ): Promise<GameResponseDto | GamePendingResponseDto> {
    // Command rather than query: the first request starts the aggregation.
    const availability = await this.commandBus.execute(
      new RequestGameSheetCommand({ gameId: params.id, language }),
    )
    if (availability.status === 'ready') {
      return GameResponseDto.fromDomain(availability.sheet)
    }
    reply
      .status(202)
      .header('Retry-After', String(AGGREGATION_POLL_INTERVAL_SECONDS))
    return GamePendingResponseDto.create(AGGREGATION_POLL_INTERVAL_SECONDS)
  }
}
