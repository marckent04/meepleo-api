import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  Post,
  Put,
  Query,
} from '@nestjs/common'
import { CommandBus, QueryBus } from '@nestjs/cqrs'
import {
  ApiBearerAuth,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger'
import { ZodResponse } from 'nestjs-zod'
import {
  DeleteGroupCommand,
  ListGroupsQuery,
  UpsertGroupCommand,
} from '@/domain/group'
import { CurrentUserId } from '../../common/decorators'
import {
  GroupCreateBodyDto,
  GroupIdParamDto,
  GroupResponseDto,
  GroupsResponseDto,
  GroupUpsertBodyDto,
  ListGroupsQueryDto,
} from '../dto'
import { ApiErrorResponses } from '../errors'

@ApiTags('groups')
@ApiBearerAuth()
@Controller({ path: 'groups', version: '1' })
export class GroupController {
  constructor(
    private readonly queryBus: QueryBus,
    private readonly commandBus: CommandBus,
  ) {}

  @Get()
  @ApiOperation({
    summary: "List the current user's groups",
    description:
      'Live groups only, or every change after `updatedSince` (tombstones included).',
  })
  @ZodResponse({ status: 200, type: GroupsResponseDto })
  @ApiErrorResponses(400, 401, 500)
  async list(
    @CurrentUserId() userId: string,
    @Query() query: ListGroupsQueryDto,
  ): Promise<GroupsResponseDto> {
    const groups = await this.queryBus.execute(
      new ListGroupsQuery({
        userId,
        updatedSince: query.updatedSince ? new Date(query.updatedSince) : null,
      }),
    )
    return GroupsResponseDto.fromDomain(groups)
  }

  @Post()
  @ApiOperation({
    summary: 'Create a group',
    description:
      'The id is generated by the client. Idempotent: replaying the same body changes nothing. An id used by another user is a 409.',
  })
  @ZodResponse({ status: 201, type: GroupResponseDto })
  @ApiErrorResponses(400, 401, 409, 422, 500)
  async create(
    @CurrentUserId() userId: string,
    @Body() body: GroupCreateBodyDto,
  ): Promise<GroupResponseDto> {
    return this.upsert(userId, body.id, body)
  }

  @Put(':id')
  @ApiOperation({
    summary: 'Create or replace a group',
    description:
      'Upsert: an unknown id creates the group. The most recent `updatedAt` wins.',
  })
  @ZodResponse({ status: 200, type: GroupResponseDto })
  @ApiErrorResponses(400, 401, 409, 422, 500)
  async replace(
    @CurrentUserId() userId: string,
    @Param() params: GroupIdParamDto,
    @Body() body: GroupUpsertBodyDto,
  ): Promise<GroupResponseDto> {
    return this.upsert(userId, params.id, body)
  }

  @Delete(':id')
  @HttpCode(204)
  @ApiOperation({
    summary: 'Delete a group',
    description: 'Idempotent soft delete (tombstone). Plays are not affected.',
  })
  @ApiResponse({ status: 204, description: 'Group is deleted' })
  @ApiErrorResponses(400, 401, 500)
  async remove(
    @CurrentUserId() userId: string,
    @Param() params: GroupIdParamDto,
  ): Promise<void> {
    await this.commandBus.execute(
      new DeleteGroupCommand({ userId, id: params.id }),
    )
  }

  private async upsert(
    userId: string,
    id: string,
    body: GroupUpsertBodyDto,
  ): Promise<GroupResponseDto> {
    const now = new Date()
    const { entity } = await this.commandBus.execute(
      new UpsertGroupCommand({
        userId,
        id,
        name: body.name,
        memberIds: body.memberIds,
        createdAt: body.createdAt ? new Date(body.createdAt) : now,
        updatedAt: body.updatedAt ? new Date(body.updatedAt) : now,
      }),
    )
    return GroupResponseDto.fromDomain(entity)
  }
}
