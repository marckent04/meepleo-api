import { createZodDto } from 'nestjs-zod'
import { z } from 'zod'
import { GROUP_MAX_MEMBERS, GROUP_NAME_MAX_LENGTH } from '@/domain/group'
import type { Group } from '@/shared/types'
import {
  SyncResponseFields,
  SyncWriteFields,
  toSyncResponse,
  UpdatedSinceQuerySchema,
} from './sync-fields.dto'

export const GroupFields = {
  name: z
    .string()
    .trim()
    .min(1)
    .max(GROUP_NAME_MAX_LENGTH)
    .describe('Group name')
    .meta({ example: 'Thursday night' }),
  memberIds: z
    .array(z.uuid())
    .min(1)
    .max(GROUP_MAX_MEMBERS)
    .describe('Players of the group (the user is implicitly a member)'),
}

export const GroupIdParamSchema = z.object({
  id: z.uuid().describe('Group identifier (UUID v7, generated by the client)'),
})
export class GroupIdParamDto extends createZodDto(GroupIdParamSchema) {}

export const GroupUpsertBodySchema = z.object({
  ...GroupFields,
  ...SyncWriteFields,
})
export class GroupUpsertBodyDto extends createZodDto(GroupUpsertBodySchema) {}

export const GroupCreateBodySchema = GroupUpsertBodySchema.extend({
  id: z.uuid().describe('Group identifier (UUID v7, generated by the client)'),
})
export class GroupCreateBodyDto extends createZodDto(GroupCreateBodySchema) {}

export class ListGroupsQueryDto extends createZodDto(UpdatedSinceQuerySchema) {}

export const GroupResponseSchema = z.object({
  id: z.uuid().describe('Group identifier'),
  name: GroupFields.name,
  memberIds: z.array(z.uuid()).describe('Players of the group'),
  matchCount: z
    .number()
    .int()
    .describe('Number of plays that include at least one member'),
  ...SyncResponseFields,
})

export class GroupResponseDto extends createZodDto(GroupResponseSchema, {
  codec: true,
}) {
  static fromDomain(group: Group): GroupResponseDto {
    return {
      id: group.id,
      name: group.name,
      memberIds: group.memberIds,
      matchCount: group.matchCount,
      ...toSyncResponse(group),
    }
  }
}

export const GroupsResponseSchema = z
  .array(GroupResponseSchema)
  .describe('Groups of the user')

export class GroupsResponseDto extends createZodDto(GroupsResponseSchema, {
  codec: true,
}) {
  static fromDomain(groups: Group[]): GroupsResponseDto {
    return groups.map((group) => GroupResponseDto.fromDomain(group))
  }
}
