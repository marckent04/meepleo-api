import { createZodDto } from 'nestjs-zod'
import { z } from 'zod'
import { PLAYER_NAME_MAX_LENGTH } from '@/domain/player'
import { PLAYER_SHAPES, type Player } from '@/shared/types'
import {
  SyncResponseFields,
  SyncWriteFields,
  toSyncResponse,
  UpdatedSinceQuerySchema,
} from './sync-fields.dto'

export const PlayerStyleFields = {
  name: z
    .string()
    .trim()
    .min(1)
    .max(PLAYER_NAME_MAX_LENGTH)
    .describe('Player name')
    .meta({ example: 'Léa' }),
  color: z
    .string()
    .regex(/^#[0-9a-fA-F]{6}$/)
    .describe('Color (#RRGGBB)')
    .meta({ example: '#E4572E' }),
  shape: z.enum(PLAYER_SHAPES).describe('Shape of the player marker'),
  handle: z
    .string()
    .trim()
    .min(1)
    .nullable()
    .optional()
    .describe('Handle of the linked Meepleo account, if any'),
  isCurrentUser: z
    .boolean()
    .optional()
    .describe('"It\'s me": at most one player per user. Defaults to false'),
}

export const PlayerIdParamSchema = z.object({
  id: z.uuid().describe('Player identifier (UUID v7, generated by the client)'),
})
export class PlayerIdParamDto extends createZodDto(PlayerIdParamSchema) {}

export const PlayerUpsertBodySchema = z.object({
  ...PlayerStyleFields,
  ...SyncWriteFields,
})
export class PlayerUpsertBodyDto extends createZodDto(PlayerUpsertBodySchema) {}

export const PlayerCreateBodySchema = PlayerUpsertBodySchema.extend({
  id: z.uuid().describe('Player identifier (UUID v7, generated by the client)'),
})
export class PlayerCreateBodyDto extends createZodDto(PlayerCreateBodySchema) {}

export class ListPlayersQueryDto extends createZodDto(
  UpdatedSinceQuerySchema,
) {}

export const PlayerResponseSchema = z.object({
  id: z.uuid().describe('Player identifier'),
  name: PlayerStyleFields.name,
  color: PlayerStyleFields.color,
  shape: PlayerStyleFields.shape,
  handle: z
    .string()
    .nullable()
    .describe('Handle of the linked Meepleo account, if any'),
  isCurrentUser: z.boolean().describe('Whether this player is the user'),
  ...SyncResponseFields,
})

export class PlayerResponseDto extends createZodDto(PlayerResponseSchema, {
  codec: true,
}) {
  static fromDomain(player: Player): PlayerResponseDto {
    return {
      id: player.id,
      name: player.name,
      color: player.color,
      shape: player.shape,
      handle: player.handle,
      isCurrentUser: player.isCurrentUser,
      ...toSyncResponse(player),
    }
  }
}

export const PlayersResponseSchema = z
  .array(PlayerResponseSchema)
  .describe('Players of the user')

export class PlayersResponseDto extends createZodDto(PlayersResponseSchema, {
  codec: true,
}) {
  static fromDomain(players: Player[]): PlayersResponseDto {
    return players.map((player) => PlayerResponseDto.fromDomain(player))
  }
}
